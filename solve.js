/** A fence's language, or null when `line` does not open one. */
function fenceOpen(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) { i++; continue; }
    break;
  }
  const lang = line.slice(3, i);
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return null;
    i++;
  }
  return lang;
}

/** Whether `line` closes a fence. */
function fenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let h = 0;
  while (h < line.length && line.charCodeAt(h) === 35) h++;
  if (h === 0 || h > 6 || h >= line.length) return null;
  const c = line.charCodeAt(h);
  if (c !== 32 && c !== 9) return null;
  let j = h;
  while (j < line.length && (line.charCodeAt(j) === 32 || line.charCodeAt(j) === 9)) j++;
  if (j >= line.length) return null;
  let k = line.length;
  while (k > j && (line.charCodeAt(k - 1) === 32 || line.charCodeAt(k - 1) === 9)) k--;
  return { depth: h, text: line.slice(j, k) };
}

/** Whether `line` is a thematic break. */
function isHR(line) {
  const c0 = line.charCodeAt(0);
  if (c0 !== 45 && c0 !== 42) return false;
  if (line.charCodeAt(1) !== c0 || line.charCodeAt(2) !== c0) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || fenceOpen(line) !== null || headingOf(line) !== null || isHR(line);
}

/** The text after "- " or "* " on `line`, or null. */
function bulletText(line) {
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** `line` as an ordered list item: its start number and text, or null. */
function orderedMatch(line) {
  let i = 0;
  while (i < line.length && line.charCodeAt(i) >= 48 && line.charCodeAt(i) <= 57) i++;
  if (i === 0 || i > 9) return null;
  if (line.charCodeAt(i) !== 46 || line.charCodeAt(i + 1) !== 32) return null;
  return { start: Number(line.slice(0, i)), text: line.slice(i + 2) };
}

/** Whether `line` continues a list item: two or more spaces, then a non-space character. */
function isContinued(line) {
  let i = 0;
  while (i < line.length && line.charCodeAt(i) === 32) i++;
  if (i < 2 || i >= line.length) return false;
  const c = line.charCodeAt(i);
  return c !== 9 && c !== 11 && c !== 12 && c !== 32 && c !== 160 && !(c >= 0x2000 && c <= 0x200a) && c !== 0x2028 && c !== 0x2029 && c !== 0x202f && c !== 0x205f && c !== 0x3000 && c !== 0xfeff;
}

/** The characters a backslash escapes, as a table over code units. */
const ESCAPABLE_CC = new Uint8Array(128);
for (const ch of '\\`*_[]()#+-.!>') ESCAPABLE_CC[ch.charCodeAt(0)] = 1;
const isEscapableCode = (c) => c < 128 && ESCAPABLE_CC[c] === 1;

/** The first index from `from` where `s` holds `what` outside a backslash escape, within `end`, or -1. */
function findUnescaped(s, what, from, end) {
  const wlen = what.length;
  for (let j = from; j + wlen <= end; j++) {
    if (s.charCodeAt(j) === 92 && j + 1 < end && isEscapableCode(s.charCodeAt(j + 1))) { j++; continue; }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, within `end`, or -1. */
function findSingleStar(s, from, end) {
  for (let j = from; j < end; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < end && isEscapableCode(s.charCodeAt(j + 1))) { j++; continue; }
    if (c !== 42) continue;
    if (j + 1 < end && s.charCodeAt(j + 1) === 42) { j++; continue; }
    return j;
  }
  return -1;
}

const SPECIAL_RE = /[\\`*\[&<>"']/g;
const WS_RE = /\s/;

/**
 * `s` from `i` to `end` rendered inline into `out`; `env.link(target)` is a link's href. Plain runs hold no
 * HTML-special character by construction (the scan only stops on one), so they are pushed as they stand.
 */
function inlineInto(s, env, out, i, end) {
  while (i < end) {
    SPECIAL_RE.lastIndex = i;
    const m = SPECIAL_RE.exec(s);
    if (m === null || m.index >= end) { out.push(s.slice(i, end)); return; }
    const j = m.index;
    if (j > i) out.push(s.slice(i, j));
    const c = s.charCodeAt(j);
    if (c === 92) {
      if (j + 1 < end && isEscapableCode(s.charCodeAt(j + 1))) { out.push(s[j + 1]); i = j + 2; }
      else { out.push('\\'); i = j + 1; }
      continue;
    }
    if (c === 96) {
      const k = s.indexOf('`', j + 1);
      if (k !== -1 && k < end && k > j + 1) {
        out.push('<code>', escapeHtml(s.slice(j + 1, k)), '</code>');
        i = k + 1;
      } else { out.push('`'); i = j + 1; }
      continue;
    }
    if (c === 42) {
      if (j + 1 < end && s.charCodeAt(j + 1) === 42) {
        const k = findUnescaped(s, '**', j + 2, end);
        if (k !== -1 && k > j + 2) {
          out.push('<strong>');
          inlineInto(s, env, out, j + 2, k);
          out.push('</strong>');
          i = k + 2;
        } else { out.push('**'); i = j + 2; }
      } else {
        const k = findSingleStar(s, j + 1, end);
        if (k !== -1 && k > j + 1) {
          out.push('<em>');
          inlineInto(s, env, out, j + 1, k);
          out.push('</em>');
          i = k + 1;
        } else { out.push('*'); i = j + 1; }
      }
      continue;
    }
    if (c === 91) {
      const k = findUnescaped(s, ']', j + 1, end);
      let t = -1;
      if (k !== -1 && k + 1 < end && s.charCodeAt(k + 1) === 40) {
        const m2 = s.indexOf(')', k + 2);
        if (m2 !== -1 && m2 < end) t = m2;
      }
      if (t !== -1) {
        const target = s.slice(k + 2, t);
        if (target !== '' && !WS_RE.test(target)) {
          out.push('<a href="', escapeHtml(env.link(target)), '">');
          inlineInto(s, env, out, j + 1, k);
          out.push('</a>');
          i = t + 1;
          continue;
        }
      }
      out.push('[');
      i = j + 1;
      continue;
    }
    out.push(ESCAPES[s[j]]);
    i = j + 1;
  }
}

/**
 * `lines` from `start` rendered: its HTML (each block on its own lines, a "\n" after the last), its table of
 * contents (every level 2 and 3 heading: level, id and its inline HTML) and its excerpt (the first paragraph's
 * inline HTML, or "").
 */
function renderMarkdown(lines, start, env, slugify) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = start;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) { i++; continue; }
    const lang = fenceOpen(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < n && !fenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const parts = ['<pre><code'];
      if (lang !== '') { parts.push(' class="language-', escapeHtml(lang), '"'); }
      parts.push('>');
      for (const l of body) { parts.push(escapeHtml(l), '\n'); }
      parts.push('</code></pre>');
      blocks.push(parts.join(''));
      continue;
    }
    const hd = headingOf(line);
    if (hd !== null) {
      const id = uniqueSlug(slugify(hd.text), ids);
      const out = [];
      inlineInto(hd.text, env, out, 0, hd.text.length);
      const html = out.join('');
      blocks.push(`<h${hd.depth} id="${id}">${html}</h${hd.depth}>`);
      if (hd.depth === 2 || hd.depth === 3) toc.push({ level: hd.depth, id, html });
      i++;
      continue;
    }
    if (isHR(line)) { blocks.push('<hr>'); i++; continue; }
    if (line.charCodeAt(0) === 62) {
      const qlines = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        let l = lines[i++];
        l = l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1);
        l = trimLine(l);
        if (l !== '') qlines.push(l);
      }
      if (qlines.length === 0) blocks.push('<blockquote>\n</blockquote>');
      else {
        const text = qlines.join('\n');
        const out = [];
        inlineInto(text, env, out, 0, text.length);
        blocks.push(`<blockquote>\n<p>${out.join('')}</p>\n</blockquote>`);
      }
      continue;
    }
    const btxt = bulletText(line);
    const ord = btxt === null ? orderedMatch(line) : null;
    if (btxt !== null || ord !== null) {
      const isOrdered = ord !== null;
      const start = isOrdered ? ord.start : 1;
      const items = [];
      while (i < n) {
        const l = lines[i];
        if (isOrdered) {
          const m = orderedMatch(l);
          if (m !== null) { items.push([trimLine(m.text)]); i++; continue; }
        } else {
          const t = bulletText(l);
          if (t !== null) { items.push([trimLine(t)]); i++; continue; }
        }
        if (isContinued(l)) { items[items.length - 1].push(trimLine(l)); i++; continue; }
        break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      const parts = [open, '\n'];
      for (const item of items) {
        const text = item.join('\n');
        const out = [];
        inlineInto(text, env, out, 0, text.length);
        parts.push('<li>', out.join(''), '</li>\n');
      }
      parts.push(`</${tag}>`);
      blocks.push(parts.join(''));
      continue;
    }
    const parts = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) parts.push(trimLine(lines[i++]));
    const text = parts.join('\n');
    const out = [];
    inlineInto(text, env, out, 0, text.length);
    const html = out.join('');
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  return { html: blocks.map((b) => `${b}\n`).join(''), toc, excerpt: excerpt ?? '' };
}

